"""
Generate knowledge/lab-catalog.md from the dbt manifest.

The catalog is the agent-facing map of the lab: every model, its layer,
materialization, upstream/downstream models, tests, and the header comment
that documents its grain and Kimball technique. It is generated (never
hand-edited) so it can't drift from the code.

Usage (from dbt/):
    dbt compile --profiles-dir ci        # or `dbt parse`; any manifest works
    python scripts/build_lab_catalog.py

CI regenerates it and fails if the committed copy is stale.
"""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT.parent / "knowledge" / "lab-catalog.md"
manifest = json.loads((ROOT / "target" / "manifest.json").read_text())
nodes = manifest["nodes"]
PKG = "kimball_lab"

models = {u: n for u, n in nodes.items() if n["resource_type"] == "model" and n["package_name"] == PKG}
tests = [n for n in nodes.values() if n["resource_type"] == "test" and n["package_name"] == PKG]
unit_tests = [n for n in manifest.get("unit_tests", {}).values() if n["package_name"] == PKG]

downstream: dict[str, list[str]] = defaultdict(list)
for uid, n in models.items():
    for dep in n["depends_on"]["nodes"]:
        if dep in models:
            downstream[dep].append(n["name"])

tests_by_model: dict[str, list[str]] = defaultdict(list)
for t in tests:
    meta = t.get("test_metadata") or {}
    label = meta.get("name") or t["name"]
    col = t.get("column_name")
    desc = f"`{label}`" + (f" on `{col}`" if col else "")
    for dep in t["depends_on"]["nodes"]:
        if dep in models:
            tests_by_model[models[dep]["name"]].append(desc)
for ut in unit_tests:
    tests_by_model[ut["model"]].append(f"unit test `{ut['name']}`")

LAYER_ORDER = ["staging", "intermediate", "marts", "semantic"]


def layer_and_area(n) -> tuple[str, str]:
    parts = n["original_file_path"].split("/")  # models/<layer>/<area>/file.sql
    layer = parts[1] if len(parts) > 2 else "other"
    area = parts[2] if len(parts) > 3 else ""
    return layer, area


def header_comment(raw: str) -> str:
    """The leading Jinja {# ... #} block or run of -- comments, cleaned."""
    m = re.search(r"\{#(.*?)#\}", raw, re.S)
    if m and raw.find("{#") < 400:
        text = m.group(1)
    else:
        lines = []
        for line in raw.splitlines():
            s = line.strip()
            if s.startswith("{{ config") or not s:
                if lines:
                    break
                continue
            if s.startswith("--"):
                lines.append(s[2:].strip())
            else:
                break
        text = "\n".join(lines)
    text = "\n".join(l.rstrip() for l in text.strip("\n").splitlines())
    # dedent
    indents = [len(l) - len(l.lstrip()) for l in text.splitlines() if l.strip()]
    pad = min(indents) if indents else 0
    return "\n".join(l[pad:] for l in text.splitlines()).strip()


def ref_names(n) -> list[str]:
    return sorted(models[d]["name"] if d in models else d.split(".")[-1] for d in n["depends_on"]["nodes"])


grouped: dict[tuple[str, str], list] = defaultdict(list)
for n in models.values():
    grouped[layer_and_area(n)].append(n)

out = [
    "# Lab catalog",
    "",
    "<!-- GENERATED by dbt/scripts/build_lab_catalog.py from the dbt manifest. Do not edit by hand. -->",
    "",
    "Every model in the Kimball Lab dbt project (`dbt/`), grouped by layer and subject area. For each model:",
    "materialization, upstream inputs, downstream consumers, tests, and the header comment that documents its",
    "grain and the Kimball technique it demonstrates. Source paths are relative to `dbt/`.",
    "",
    f"Totals: {len(models)} models, {len(tests)} data tests, {len(unit_tests)} unit tests.",
    "",
    "## Contents",
    "",
]
keys = sorted(grouped, key=lambda k: (LAYER_ORDER.index(k[0]) if k[0] in LAYER_ORDER else 99, k[1]))
for layer, area in keys:
    title = f"{layer}/{area}" if area else layer
    names = ", ".join(f"`{m['name']}`" for m in sorted(grouped[(layer, area)], key=lambda m: m["name"]))
    out.append(f"- **{title}**: {names}")
out.append("")

for layer, area in keys:
    title = f"{layer}/{area}" if area else layer
    out += [f"## {title}", ""]
    for n in sorted(grouped[(layer, area)], key=lambda m: m["name"]):
        cfg = n["config"]
        mat = cfg.get("materialized")
        extras = []
        if cfg.get("unique_key"):
            extras.append(f"unique_key={cfg['unique_key']}")
        if cfg.get("incremental_strategy"):
            extras.append(f"strategy={cfg['incremental_strategy']}")
        if (cfg.get("contract") or {}).get("enforced"):
            extras.append("contract enforced")
        out.append(f"### `{n['name']}`")
        out.append("")
        out.append(f"- **File:** `{n['original_file_path']}`")
        out.append(f"- **Materialized:** {mat}" + (f" ({', '.join(extras)})" if extras else ""))
        if n.get("description"):
            out.append(f"- **Description:** {n['description'].strip()}")
        refs = ref_names(n)
        if refs:
            out.append(f"- **Reads:** {', '.join(f'`{r}`' for r in refs)}")
        if downstream.get(n["unique_id"]):
            out.append(f"- **Used by:** {', '.join(f'`{d}`' for d in sorted(downstream[n['unique_id']]))}")
        if tests_by_model.get(n["name"]):
            out.append(f"- **Tests:** {'; '.join(sorted(set(tests_by_model[n['name']])))}")
        hdr = header_comment(n["raw_code"])
        if hdr:
            out += ["", "```text", hdr, "```"]
        out.append("")

# Semantic layer
sms = [s for s in manifest.get("semantic_models", {}).values() if s["package_name"] == PKG]
mets = [m for m in manifest.get("metrics", {}).values() if m["package_name"] == PKG]
if sms or mets:
    out += ["## Semantic layer", ""]
    for s in sorted(sms, key=lambda x: x["name"]):
        measures = ", ".join(m["name"] for m in s.get("measures", []))
        dims = ", ".join(d["name"] for d in s.get("dimensions", []))
        out.append(f"- **semantic model `{s['name']}`**: measures [{measures}]; dimensions [{dims}]")
    for m in sorted(mets, key=lambda x: x["name"]):
        out.append(f"- **metric `{m['name']}`** ({m['type']}): {m.get('description') or m.get('label') or ''}".rstrip())
    out.append("")

# Analyses and singular tests
analyses = sorted((n for n in nodes.values() if n["resource_type"] == "analysis" and n["package_name"] == PKG), key=lambda n: n["name"])
if analyses:
    out += ["## Analyses (business-question queries)", ""]
    for a in analyses:
        first = header_comment(a["raw_code"]).splitlines()
        out.append(f"- `{a['original_file_path']}`: {first[0] if first else ''}")
    out.append("")

singular = sorted((t for t in tests if not t.get("test_metadata")), key=lambda t: t["name"])
if singular:
    out += ["## Singular tests", ""]
    for t in singular:
        first = header_comment(t["raw_code"]).splitlines()
        out.append(f"- `{t['original_file_path']}`: {first[0] if first else ''}")
    out.append("")

OUT.parent.mkdir(exist_ok=True)
OUT.write_text("\n".join(out).rstrip() + "\n")
print(f"wrote {OUT.relative_to(ROOT.parent)} ({len(models)} models)")
